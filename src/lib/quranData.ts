/**
 * Fetch verses dynamically from public Quran API if available, or fallback to curated list
 */
export async function fetchSurahVerses(surahNumber: number): Promise<AyahItem[]> {
  if (CURATED_SURAHS[surahNumber]) {
    return CURATED_SURAHS[surahNumber];
  }

  try {
    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), 4500);

    const [arabicRes, englishRes] = await Promise.all([
      fetch(`https://api.alquran.cloud/v1/surah/${surahNumber}/quran-uthmani`, {
        signal: controller.signal,
      }),
      fetch(`https://api.alquran.cloud/v1/surah/${surahNumber}/en.sahih`, {
        signal: controller.signal,
      }),
    ]);

    clearTimeout(timeout);

    if (arabicRes.ok && englishRes.ok) {
      const arabicData = await arabicRes.json();
      const englishData = await englishRes.json();

      const arabicAyahs = arabicData.data?.ayahs || [];
      const englishAyahs = englishData.data?.ayahs || [];

      return arabicAyahs.map((item: any, idx: number) => {
        const paddedSurah = String(surahNumber).padStart(3, "0");
        const paddedAyah = String(item.numberInSurah).padStart(3, "0");
        return {
          numberInSurah: item.numberInSurah,
          textArabic: item.text,
          transliteration: `Ayah ${item.numberInSurah}`,
          translation: englishAyahs[idx]?.text || "",
          audioUrl: `https://everyayah.com/data/Alafasy_128kbps/${paddedSurah}${paddedAyah}.mp3`,
          juz: item.juz || 1,
        };
      });
    }
  } catch (e) {
    console.warn("Could not fetch remote Quran data, returning fallback", e);
  }

  // Fallback if network unavailable
  return CURATED_SURAHS[1];
}

